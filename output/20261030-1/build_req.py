import pos_tool as t

POS = '/tmp/gwtc/repo/baseline/Tutti新框架_20261021.pos'
ROOT = t.root_of(t.load(POS))
IDX = {n['id']: n for n, _ in t.iter_nodes(ROOT)}
REASON = 'Agent GUI需求更新（2026-10-30）'
UPD, ADD = [], []

def full(p):
    m = [k for k in IDX if k.startswith(p)]
    assert len(m) == 1, (p, len(m))
    return m[0]

def retitle(p, new, reason=REASON):
    nid = full(p)
    if IDX[nid]['title'] != new:
        UPD.append({'id': nid, 'from': IDX[nid]['title'], 'to': new, 'reason': reason})

def set_step(p, prefix, text):
    cid = full(p)
    ks = [c for c in t.kids(IDX[cid]) if t.strip(c.get('title', '')).startswith(prefix)]
    if ks:
        assert len(ks) == 1, (p, prefix, len(ks))
        if ks[0]['title'] != text:
            UPD.append({'id': ks[0]['id'], 'from': ks[0]['title'], 'to': text, 'reason': REASON})
    else:
        ADD.append({'parent_id': cid, 'nodes': [{'title': text}]})

def add(p, nodes):
    ADD.append({'parent_id': full(p), 'nodes': nodes})

def case(prio, title, pre, op, expect, note=None):
    tag = {'P0': '🔴【P0】', 'P1': '🟠【P1】', 'P2': '🟡【P2】'}[prio]
    n = {'case': tag + title, 'pre': pre, 'op': op, 'expect': expect}
    if note:
        n['note'] = note
    return n

def grp(title, children):
    return {'title': title, 'children': children}

def expect_text(lines):
    return '预期：\n' + '\n'.join(f'{i}) {l}' for i, l in enumerate(lines, 1))

