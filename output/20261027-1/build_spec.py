def G(title, normal=(), abnormal=(), edge=(), desc=None):
    ch = [{"title": "说明：" + desc}] if desc else []
    for name, lst in (("正常场景", normal), ("异常场景", abnormal), ("边界场景", edge)):
        if lst:
            ch.append({"title": name, "children": list(lst)})
    return {"title": title, "children": ch}

